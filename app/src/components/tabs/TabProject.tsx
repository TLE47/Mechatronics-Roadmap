import React, { useEffect, useMemo, useState } from 'react';
import { Copy, Cpu, PackageSearch } from 'lucide-react';
import projectDocument from '../../data/capstoneProject.json';
import { missingProjectObject } from '../../projectRef.ts';
import {
  readProject,
  requirementPasses,
  testsForRequirement,
  type ProjectComponent,
} from '../../projectModel';
import { filterProjectObjects, findProjectObject } from '../../projectQueries';
import { ProjectBrowser } from '../project/ProjectBrowser';

interface TabProjectProps {
  /**
   * A part another surface asked to open, by its stable id (`WorkflowNode.projectRef`). The nonce
   * makes a second ask for the same part fire: a badge pressed twice is two gestures, not one.
   */
  focus?: { id: string; nonce: number } | null;
  /** Opens the Requirements view on a requirement this part helps meet, by its stable id. */
  onOpenRequirement: (requirementId: string) => void;
}

// Generated by `npm run gen:project` from the capstone's own EDA report, then read strictly:
// the summary this page prints is the rows' own sum, never a second number typed here.
const PROJECT = readProject(projectDocument);

/**
 * Project Mode: the project's parts as objects with one id (`components/tabs/TabProject.tsx`).
 *
 * A second view over `projectModel.ts`, not a second copy of the bill of materials: the PCB lab
 * prints the same rows for their ratings, the workflow lets a card cite one by id, and this page is
 * where an id becomes a designation, a part number, a description and a cost. Search accepts any of
 * those words, so a learner holding `08-capstone1-foc-eda/u6` from a card can reach it here.
 */
export const TabProject: React.FC<TabProjectProps> = ({ focus, onOpenRequirement }) => {
  const [query, setQuery] = useState('');
  const [selectedId, setSelectedId] = useState<string>(PROJECT.components[0].id);
  const [copied, setCopied] = useState(false);

  const filtered = useMemo(
    () => filterProjectObjects<ProjectComponent>('component', PROJECT, query),
    [query]
  );
  // A selection that the search has filtered out falls back to the first match, so the detail card
  // never describes a row the list no longer shows.
  const selected: ProjectComponent | null =
    filtered.find((part) => part.id === selectedId) ?? filtered[0] ?? null;
  const asked = focus ? findProjectObject<ProjectComponent>(PROJECT, 'component', focus.id) : null;
  const partRequirements = selected
    ? PROJECT.requirements.filter((requirement) => requirement.partIds.includes(selected.id))
    : [];

  useEffect(() => {
    if (!focus) return;
    if (findProjectObject<ProjectComponent>(PROJECT, 'component', focus.id)) {
      setQuery('');
      setSelectedId(focus.id);
    }
  }, [focus?.id, focus?.nonce]);

  const copyId = async (id: string) => {
    try {
      await navigator.clipboard.writeText(id);
      setCopied(true);
      window.setTimeout(() => setCopied(false), 1600);
    } catch {
      setCopied(false);
    }
  };

  return (
    <div data-testid="project-mode" className="space-y-3">
      <header className="rounded-xl border border-line bg-panel p-4">
        <div className="flex flex-wrap items-baseline justify-between gap-2">
          <h1 className="flex items-center gap-2 text-base font-bold text-ink">
            <PackageSearch className="h-4 w-4 text-accent" aria-hidden="true" />
            Project Mode
          </h1>
          <span className="font-mono text-[11px] text-muted" data-testid="project-id">
            {PROJECT.id}
          </span>
        </div>
        <p className="mt-1 text-xs text-muted">
          Every part this project is built from, with the id a workflow card, a schematic and this
          page all use for it.
        </p>
        <p className="mt-2 font-mono text-[11.5px] text-body" data-testid="project-summary">
          {PROJECT.summary.lines} lines · {PROJECT.summary.placements} placements · $
          {PROJECT.summary.costUsd.toFixed(2)}
        </p>
      </header>

      {focus && !asked && (
        <p
          data-testid="project-missing"
          role="status"
          className="rounded-lg border border-amber/60 bg-amber/10 px-3 py-2 text-xs text-amber"
        >
          That card cites <span className="font-mono">{focus.id}</span>. {missingProjectObject(focus.id)}
        </p>
      )}

      <div className="grid gap-3 lg:grid-cols-[minmax(0,1fr)_22rem]">
        <ProjectBrowser
          kind="component"
          project={PROJECT}
          items={filtered}
          query={query}
          onQuery={setQuery}
          selectedId={selected?.id ?? null}
          onSelect={setSelectedId}
        />

        <aside
          data-testid="project-detail"
          aria-live="polite"
          className="rounded-xl border border-line bg-panel p-3"
        >
          {selected ? (
            <div className="space-y-2">
              <div className="flex items-start justify-between gap-2">
                <div className="min-w-0">
                  <h2 className="truncate text-sm font-bold text-ink">{selected.refDes}</h2>
                  <p className="truncate font-mono text-[11px] text-accent">{selected.mpn}</p>
                </div>
                <Cpu className="h-4 w-4 shrink-0 text-faint" aria-hidden="true" />
              </div>
              <div className="flex items-center gap-1.5">
                <code
                  data-testid="project-part-id"
                  title={selected.id}
                  className="min-w-0 flex-1 truncate rounded bg-canvas px-1.5 py-1 font-mono text-[10.5px] text-body"
                >
                  {selected.id}
                </code>
                <button
                  type="button"
                  data-testid="project-copy-id"
                  onClick={() => copyId(selected.id)}
                  className="flex min-h-8 shrink-0 items-center gap-1 rounded border border-line bg-raise px-2 text-[11px] text-body hover:bg-elevate"
                >
                  <Copy className="h-3 w-3" aria-hidden="true" />
                  {copied ? 'Copied' : 'Copy id'}
                </button>
              </div>
              <dl className="grid grid-cols-2 gap-x-3 gap-y-1 text-[11.5px]">
                <dt className="text-faint">Category</dt>
                <dd className="text-body">{selected.category}</dd>
                <dt className="text-faint">Rating</dt>
                <dd className="text-body">{selected.rating}</dd>
                <dt className="text-faint">Derating</dt>
                <dd className={selected.derated ? 'text-emerald' : 'text-rose'}>
                  {selected.derated ? 'passes' : 'fails'}
                </dd>
                <dt className="text-faint">Placements</dt>
                <dd className="font-mono text-body">
                  {selected.qty} × ${selected.unitCostUsd.toFixed(2)}
                </dd>
                <dt className="text-faint">Line cost</dt>
                <dd className="font-mono text-body">
                  ${(selected.qty * selected.unitCostUsd).toFixed(2)}
                </dd>
              </dl>
              <p className="text-[12px] leading-snug text-muted">{selected.description}</p>
              {partRequirements.length > 0 && (
                <div
                  data-testid="project-requirements"
                  className="border-t border-line-soft pt-2"
                >
                  <h3 className="text-[10.5px] font-semibold uppercase tracking-wide text-muted">
                    Requirements it helps meet
                  </h3>
                  <ul className="mt-1 space-y-1">
                    {partRequirements.map((requirement) => {
                      const test = testsForRequirement(PROJECT.tests, requirement.id)[0];
                      const met = requirementPasses(requirement, PROJECT.tests);
                      return (
                        <li key={requirement.id}>
                          <button
                            type="button"
                            data-testid={`project-req-${PROJECT.requirements.indexOf(requirement)}`}
                            data-requirement-id={requirement.id}
                            onClick={() => onOpenRequirement(requirement.id)}
                            className="flex w-full items-baseline gap-2 rounded border border-line bg-raise px-2 py-1 text-left hover:bg-elevate"
                          >
                            <span className="shrink-0 font-mono text-[10px] text-accent">
                              {requirement.ref}
                            </span>
                            <span className="min-w-0 flex-1">
                              <span className="block truncate text-[11.5px] text-body">
                                {requirement.title}
                              </span>
                              <span className="block truncate font-mono text-[9.5px] text-faint">
                                {test?.ref ?? 'no test'} · {met ? 'met' : 'missed'}
                              </span>
                            </span>
                          </button>
                        </li>
                      );
                    })}
                  </ul>
                </div>
              )}
            </div>
          ) : (
            <p className="text-sm text-muted">Pick a part to see its id, rating and cost.</p>
          )}
          <p className="mt-3 border-t border-line-soft pt-2 font-mono text-[10px] text-faint">
            generated from {PROJECT.source}
          </p>
        </aside>
      </div>
    </div>
  );
};
