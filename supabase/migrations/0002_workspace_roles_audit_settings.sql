-- Accounts, phase 2–5: opt-in workspace sync, roles, audit and public site settings.
--
-- Four tables, four different audiences:
--
--   mechalab_workspace   the learner's own drafts/notes copy — own row only, no deletes from the client
--   mechalab_roles       who is an admin — readable by its owner, writable by nobody in the browser
--   mechalab_audit       what an admin did — no browser grants at all; read through `admin-action`
--   mechalab_site_settings  an announcement and a few flags — public read, server-only write
--
-- The grants are as deliberate as the policies: Supabase's default grants give `anon` and
-- `authenticated` every verb on a new public table, and a policy cannot take a verb away. Every table
-- below therefore revokes first. `tests/test_accounts_schema.py` reads this file and fails if a table
-- is created without RLS, or if the role table ever grows a write grant.

-- ── Opt-in drafts, notes and highlights ───────────────────────────────────────────────────────────
create table if not exists public.mechalab_workspace (
  user_id uuid primary key references auth.users (id) on delete cascade,
  workspace jsonb not null,
  updated_at timestamptz not null default now()
);

alter table public.mechalab_workspace enable row level security;
alter table public.mechalab_workspace force row level security;

revoke all on table public.mechalab_workspace from anon, authenticated;
grant select, insert, update on table public.mechalab_workspace to authenticated;

drop policy if exists "read own workspace" on public.mechalab_workspace;
create policy "read own workspace" on public.mechalab_workspace
  for select using (auth.uid() = user_id);

drop policy if exists "insert own workspace" on public.mechalab_workspace;
create policy "insert own workspace" on public.mechalab_workspace
  for insert with check (auth.uid() = user_id);

drop policy if exists "update own workspace" on public.mechalab_workspace;
create policy "update own workspace" on public.mechalab_workspace
  for update using (auth.uid() = user_id) with check (auth.uid() = user_id);

-- ── Roles, stored apart from anything a learner can edit ──────────────────────────────────────────
create table if not exists public.mechalab_roles (
  user_id uuid primary key references auth.users (id) on delete cascade,
  role text not null check (role in ('learner', 'admin')),
  granted_at timestamptz not null default now(),
  granted_by uuid references auth.users (id) on delete set null
);

alter table public.mechalab_roles enable row level security;
alter table public.mechalab_roles force row level security;

-- Select only. There is no insert, update or delete grant for `anon` or `authenticated`, and no
-- policy that would allow one: a role is written by `admin-action` with the service-role key, or by an
-- operator in the SQL editor. That is what makes "no account can grant itself a role" structural
-- rather than a rule in React.
revoke all on table public.mechalab_roles from anon, authenticated;
grant select on table public.mechalab_roles to authenticated;

drop policy if exists "read own role" on public.mechalab_roles;
create policy "read own role" on public.mechalab_roles
  for select using (auth.uid() = user_id);

-- A security-definer helper so a future policy can ask "is the caller an admin?" without recursing
-- into this table's own policy. Its search_path is pinned, and it only ever answers about auth.uid().
create or replace function public.mechalab_is_admin()
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select exists (
    select 1 from public.mechalab_roles r
    where r.user_id = auth.uid() and r.role = 'admin'
  );
$$;

revoke all on function public.mechalab_is_admin() from public;
grant execute on function public.mechalab_is_admin() to authenticated;

-- ── Audit log: written and read only by the server ────────────────────────────────────────────────
create table if not exists public.mechalab_audit (
  id bigint generated by default as identity primary key,
  at timestamptz not null default now(),
  actor uuid references auth.users (id) on delete set null,
  action text not null,
  detail jsonb not null default '{}'::jsonb
);

alter table public.mechalab_audit enable row level security;
alter table public.mechalab_audit force row level security;
revoke all on table public.mechalab_audit from anon, authenticated;

create index if not exists mechalab_audit_at_idx on public.mechalab_audit (at desc);

-- ── Public site settings: an announcement line and a fixed flag list ──────────────────────────────
create table if not exists public.mechalab_site_settings (
  key text primary key,
  value jsonb not null,
  updated_at timestamptz not null default now(),
  updated_by uuid references auth.users (id) on delete set null
);

alter table public.mechalab_site_settings enable row level security;
alter table public.mechalab_site_settings force row level security;

revoke all on table public.mechalab_site_settings from anon, authenticated;
grant select on table public.mechalab_site_settings to anon, authenticated;

drop policy if exists "site settings are public" on public.mechalab_site_settings;
create policy "site settings are public" on public.mechalab_site_settings
  for select using (true);

