#!/usr/bin/env python3
"""Write the ten-step spine the app and the pages both number by.

`scripts/route_model.py` is already the one declaration of the learner-facing route: ten steps,
each with a title, an outcome, a start page and the pages/modules it contains. The README table,
`SIM_ROUTE.md`, `DEPTH.md`, `MINIMUM.md` and `check_consistency.py` all read it. The workbench did
not: it showed passes (1-3) and their eight tracks, so the same learner saw "Step 1 of 10" on P.1
and "Tier 1 · Step 1 / 8" in the roadmap, and the Python on-ramp had no step at all.

This generator copies the ten steps into `app/src/data/spineData.ts` so the app can render the same
numbers the pages print. It copies, it does not paraphrase: the titles and outcomes are route_model's
strings, the lesson/module lists are its lists. `--check` compares the committed file with what the
model renders now, so a step cannot be added or renamed on one surface only.

A typed module rather than JSON, for the same reason `pythonLessonsData.ts` is one: Node's type
stripping runs `app/src/spine.ts` directly, so `scripts/test_spine.mjs` can check the join between
the spine and the 86 workbench entries without a bundler, and a JSON import would need a loader flag.

Usage:
    python3 scripts/generate_spine_data.py            # write app/src/data/spineData.ts
    python3 scripts/generate_spine_data.py --check    # exit 1 if it is stale
"""

import argparse
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "app", "src", "data", "spineData.ts")

sys.path.insert(0, os.path.join(ROOT, "scripts"))
import route_model  # noqa: E402


def payload():
    steps = []
    for step in route_model.STEPS:
        steps.append(
            {
                "number": step["number"],
                "slug": step["slug"],
                "title": step["title"],
                "outcome": step["outcome"],
                "start": step["start"],
                "lessons": list(step["lessons"]),
                "modules": list(step["modules"]),
                "optional": list(step["optional"]),
            }
        )
    return {
        "source": "scripts/route_model.py",
        "steps": steps,
    }


def render():
    lines = [
        "// Auto-generated by scripts/generate_spine_data.py — do not edit manually",
        "//",
        "// The ten steps scripts/route_model.py declares, copied for the app. The numbers,",
        "// titles, outcomes and start pages are the model's own strings; the lesson and module",
        "// lists are its lists. `--check` fails when this file drifts from the model, so a step",
        "// cannot be added or renamed on one surface only.",
        "export interface SpineStepData {",
        "  /** 1..10, the number every surface prints. */",
        "  number: number;",
        "  slug: string;",
        "  title: string;",
        "  outcome: string;",
        "  /** The page a learner starts this step on. */",
        "  start: string;",
        "  lessons: string[];",
        "  modules: string[];",
        "  optional: string[];",
        "}",
        "",
        "export const SPINE_SOURCE: SpineStepData[] = [",
    ]
    for step in payload()["steps"]:
        fields = [
            ("number", json.dumps(step["number"])),
            ("slug", json.dumps(step["slug"], ensure_ascii=False)),
            ("title", json.dumps(step["title"], ensure_ascii=False)),
            ("outcome", json.dumps(step["outcome"], ensure_ascii=False)),
            ("start", json.dumps(step["start"], ensure_ascii=False)),
        ]
        for key in ("lessons", "modules", "optional"):
            fields.append((key, json.dumps(step[key], ensure_ascii=False)))
        lines.append("  {")
        for name, value in fields:
            lines.append("    %s: %s," % (name, value))
        lines.append("  },")
    lines.append("];")
    lines.append("")
    return "\n".join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="report a stale file instead of writing")
    args = parser.parse_args(argv)

    rendered = render()
    current = ""
    if os.path.exists(OUT):
        with open(OUT, encoding="utf-8") as handle:
            current = handle.read()

    if args.check:
        if current != rendered:
            print(
                "ERROR: %s is stale; run python3 scripts/generate_spine_data.py"
                % os.path.relpath(OUT, ROOT)
            )
            return 1
        print("OK: the app's ten-step spine matches scripts/route_model.py.")
        return 0

    if current == rendered:
        print("spineData.ts already current")
        return 0
    with open(OUT, "w", encoding="utf-8") as handle:
        handle.write(rendered)
    print("wrote %s (%d steps)" % (os.path.relpath(OUT, ROOT), len(payload()["steps"])))
    return 0


if __name__ == "__main__":
    sys.exit(main())
