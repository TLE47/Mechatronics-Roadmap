#!/usr/bin/env bash
#
# Bootstrap the Chromium runtime libraries and fonts the browser gates need.
#
# Playwright ships the browser, not the Linux distribution's shared libraries. On a host without
# those libraries Chromium exits before the first page loads (`libnspr4.so: cannot open shared
# object file`). This script builds a private sysroot outside the worktree with `apt-get download`,
# so it needs neither root nor a system-wide install, and writes the environment to source:
#
#   bash scripts/setup_browser_deps.sh
#   source "${XDG_DATA_HOME:-$HOME/.local/share}/mechalab-browser-deps/env.sh"
#   npm run check:all
#   npx tsc -b
#
# `npm ci` and `npx playwright install chromium chromium-headless-shell` are the caller's job; the
# browser binaries themselves are not distribution packages.
#
# Linux x86_64 with apt-get and dpkg-deb (Ubuntu 24.04 is the tested host). Set
# MECHALAB_BROWSER_DEPS to choose another directory outside the worktree.

set -euo pipefail

ROOT="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd)"
DEPS_DIR="${MECHALAB_BROWSER_DEPS:-${XDG_DATA_HOME:-$HOME/.local/share}/mechalab-browser-deps}"

case "$DEPS_DIR" in
  "$ROOT" | "$ROOT"/*)
    echo "refusing to put browser dependencies inside the worktree: $DEPS_DIR" >&2
    exit 2
    ;;
esac

if [ "$(uname -m)" != "x86_64" ]; then
  echo "this bootstrap is written for Linux x86_64; got $(uname -m)" >&2
  exit 2
fi

for tool in apt-get dpkg-deb ldd; do
  if ! command -v "$tool" >/dev/null 2>&1; then
    echo "missing $tool; this bootstrap needs apt-get, dpkg-deb and ldd" >&2
    exit 2
  fi
done

APT_LISTS="$DEPS_DIR/apt/lists"
APT_CACHE="$DEPS_DIR/apt/cache"
DEBS="$DEPS_DIR/debs"
SYSROOT="$DEPS_DIR/sysroot"
FONT_CACHE="$DEPS_DIR/fontcache"
LIBDIR="$SYSROOT/usr/lib/x86_64-linux-gnu"

# Playwright's Chromium needs these directly, plus the libraries those packages load. The list was
# read from `ldd` on both Playwright Chromium binaries, then reduced until neither had a `not found`.
PACKAGES=(
  libnspr4
  libnss3
  libatk1.0-0t64
  libatk-bridge2.0-0t64
  libatspi2.0-0t64
  libcups2t64
  libxkbcommon0
  libasound2t64
  libcairo2
  libpango-1.0-0
  libxcomposite1
  libxdamage1
  libxfixes3
  libxrandr2
  libavahi-common3
  libavahi-client3
  libpng16-16t64
  libfontconfig1
  libfreetype6
  libxrender1
  libxcb-render0
  libpixman-1-0
  libthai0
  libharfbuzz0b
  libxi6
  libdatrie1
  libfribidi0
  libgraphite2-3
  fontconfig-config
  fonts-dejavu-core
  fonts-liberation
)

mkdir -p "$APT_LISTS/partial" "$APT_CACHE/archives/partial" "$DEBS" "$FONT_CACHE"

apt_options=(
  -o "Dir::State::lists=$APT_LISTS"
  -o "Dir::Cache=$APT_CACHE"
  -o "APT::Sandbox::User=$(id -un)"
  -o "Debug::NoLocking=1"
)

echo "Refreshing package lists in $DEPS_DIR/apt ..."
apt-get "${apt_options[@]}" update

echo "Downloading Chromium runtime packages ..."
rm -f "$DEBS"/*.deb
(
  cd "$DEBS"
  apt-get "${apt_options[@]}" download "${PACKAGES[@]}"
)

echo "Extracting into $SYSROOT ..."
rm -rf "$SYSROOT"
mkdir -p "$SYSROOT"
for deb in "$DEBS"/*.deb; do
  dpkg-deb -x "$deb" "$SYSROOT"
done

cat >"$DEPS_DIR/fonts.conf" <<EOF
<?xml version="1.0"?>
<!DOCTYPE fontconfig SYSTEM "urn:fontconfig:fonts.dtd">
<fontconfig>
  <dir>$SYSROOT/usr/share/fonts</dir>
  <cachedir>$FONT_CACHE</cachedir>
  <include ignore_missing="yes">conf.d</include>
</fontconfig>
EOF

cat >"$DEPS_DIR/env.sh" <<EOF
# Generated by scripts/setup_browser_deps.sh. Source this before the browser gates.
export LD_LIBRARY_PATH="$LIBDIR\${LD_LIBRARY_PATH:+:\$LD_LIBRARY_PATH}"
export FONTCONFIG_FILE="$DEPS_DIR/fonts.conf"
export FONTCONFIG_PATH="$SYSROOT/etc/fonts"
# Keep the scripts' headless-shell lookup and Playwright's executablePath() on the same cache.
export PLAYWRIGHT_BROWSERS_PATH="\${PLAYWRIGHT_BROWSERS_PATH:-$HOME/.cache/ms-playwright}"
EOF

# shellcheck disable=SC1090
source "$DEPS_DIR/env.sh"

found=0
missing=0
for binary in \
  "$HOME"/.cache/ms-playwright/chromium-*/chrome-linux64/chrome \
  "$HOME"/.cache/ms-playwright/chromium_headless_shell-*/chrome-headless-shell-linux64/chrome-headless-shell; do
  [ -x "$binary" ] || continue
  found=1
  if ldd "$binary" | grep -q 'not found'; then
    echo "unresolved libraries for $binary:" >&2
    ldd "$binary" | grep 'not found' >&2 || true
    missing=1
  fi
done

if [ "$found" -eq 0 ]; then
  echo "no Playwright Chromium found; run: npx playwright install chromium chromium-headless-shell" >&2
  exit 1
fi
if [ "$missing" -ne 0 ]; then
  exit 1
fi

echo "Browser dependencies ready: $DEPS_DIR"
echo "Next:"
echo "  source \"$DEPS_DIR/env.sh\""
echo "  npm run check:all"
echo "  npx tsc -b"
