#!/usr/bin/env python3
"""Generate app/src/data/mechalabPlant.ts from the shared plant.

The workbench runs Python in Pyodide with only the files we hand it, so the shared plant has to
travel as *source text*: this embeds `resources/plants/mechalab_plant.py` (the executable model) and
the values from `resources/plants/tier1_arm_motor.yaml` in a TypeScript module that
`app/src/components/tabs/TabPyodideRunner.tsx` writes into Pyodide's filesystem before your code
runs. That is what makes `import mechalab_plant` work in a lesson exercise, in the same workbench
that already grades the Tier 1 lessons.

`--check` (CI) fails when the generated file is stale, so editing the plant without regenerating is
caught the same way a stale lesson dataset is. Contract borrowed from
`scripts/generate_python_lessons_data.py`, which does this for the lesson dataset.

Exit-code family: typed (0 ok, 1 the generated file is stale or the plant is malformed, 2 usage).
"""

import argparse
import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PLANT_PY = os.path.join(ROOT, "resources", "plants", "mechalab_plant.py")
PLANT_YAML = os.path.join(ROOT, "resources", "plants", "tier1_arm_motor.yaml")
OUT_PATH = os.path.join(ROOT, "app", "src", "data", "mechalabPlant.ts")
PLANT_FILENAME = "mechalab_plant.py"

VERSION = "1.0.0"


def parse_flat_yaml(path):
    """Read the plant YAML: flat `dotted.key: number  # provenance` lines, comments and blanks.

    A separate, deliberately simple reader from the one the generator is checked against; two
    independent readers of the same file catch a parser that quietly drops a row.
    """
    values = {}
    with open(path, encoding="utf-8") as handle:
        for number, raw in enumerate(handle, start=1):
            line = raw.strip()
            if not line or line.startswith("#"):
                continue
            key, separator, rest = line.partition(":")
            if not separator:
                raise ValueError("%s:%d is not a `key: value` line: %r" % (path, number, line))
            key = key.strip()
            value_text = rest.split("#")[0].strip()
            try:
                value = (
                    float(value_text) if ("." in value_text or "e" in value_text) else int(value_text)
                )
            except ValueError:
                raise ValueError(
                    "%s:%d value %r is not a number - this file carries values, not prose"
                    % (path, number, value_text)
                )
            if key in values:
                raise ValueError("%s:%d repeats the key %r" % (path, number, key))
            values[key] = value
    return values


def plant_source():
    with open(PLANT_PY, "r", encoding="utf-8") as handle:
        return handle.read()


def render(values, source):
    return (
        "// Auto-generated by scripts/generate_plant_data.py — do not edit manually\n"
        "// Executable model: resources/plants/mechalab_plant.py\n"
        "// Values and provenance: resources/plants/tier1_arm_motor.yaml\n"
        "// Regenerate with: python3 scripts/generate_plant_data.py\n\n"
        "/** Name the shared plant is written as inside Pyodide's filesystem. */\n"
        "export const MECHALAB_PLANT_FILENAME = "
        + json.dumps(PLANT_FILENAME)
        + ";\n\n"
        "/** The shared plant's Python source, verbatim, so `import mechalab_plant` works. */\n"
        "export const MECHALAB_PLANT_PY: string = "
        + json.dumps(source)
        + ";\n\n"
        "/** The plant's values, keyed exactly as `tier1_arm_motor.yaml` writes them. */\n"
        "export const MECHALAB_PLANT_VALUES: Record<string, number> = "
        + json.dumps(values, indent=2, sort_keys=True)
        + ";\n"
    )


def main(argv=None):
    parser = argparse.ArgumentParser(
        prog="generate_plant_data.py",
        description="Embed the shared plant (resources/plants/) as app/src/data/mechalabPlant.ts",
        epilog="Exit-code family: typed",
    )
    parser.add_argument("--check", action="store_true", help="verify the generated file is in sync")
    parser.add_argument("--json", action="store_true", help="print the plant's values and exit")
    parser.add_argument("-q", "--quiet", action="store_true", help="print nothing on success")
    parser.add_argument("-V", "--version", action="version", version="%(prog)s " + VERSION)
    args = parser.parse_args(argv)

    try:
        values = parse_flat_yaml(PLANT_YAML)
    except (OSError, ValueError) as err:
        print("ERROR: %s" % err, file=sys.stderr)
        return 1

    if args.json:
        print(json.dumps(values, indent=2, sort_keys=True))
        return 0

    try:
        content = render(values, plant_source())
    except OSError as err:
        print("ERROR: %s" % err, file=sys.stderr)
        return 1

    if args.check:
        if not os.path.exists(OUT_PATH):
            print("ERROR: %s does not exist. Run python3 scripts/generate_plant_data.py" % OUT_PATH)
            return 1
        with open(OUT_PATH, "r", encoding="utf-8") as handle:
            existing = handle.read()
        if existing != content:
            print(
                "ERROR: %s is out of sync with resources/plants/. "
                "Run `python3 scripts/generate_plant_data.py`." % OUT_PATH
            )
            return 1
        if not args.quiet:
            print("OK: %s is in sync with all %d plant values." % (OUT_PATH, len(values)))
        return 0

    with open(OUT_PATH, "w", encoding="utf-8") as handle:
        handle.write(content)
    if not args.quiet:
        print("Generated %s with %d plant values." % (OUT_PATH, len(values)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
