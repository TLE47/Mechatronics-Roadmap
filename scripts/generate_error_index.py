#!/usr/bin/env python3
"""Generate `app/src/data/errorIndex.ts` from `docs/ERROR_EXPLAINER.md`.

The page is the source and the app is a second reader of it: a learner who hits an exception in the
runner should not have to leave the tab to find out which of the fifteen failures it is. Emitting the
app's copy from the page is what keeps the two from drifting - editing an entry and forgetting the app
is a `--check` failure, not a quietly stale card.

What is taken from each `## N. Title` entry:

- `number` and `title` (backticks stripped: they are Markdown emphasis, not text to show);
- `means`, the `**What it means.**` paragraph, collapsed to one line;
- `checks`, the `**Check first.**` bullets, with wrapped lines rejoined;
- `source`, the first relative link under `**Where it comes from.**`.

The match is derived from the heading rather than hand-written, because the heading *is* the symptom a
learner sees: `ValueError: matrix columns must match vector length` yields the exception class and the
message to look for, `ZeroDivisionError in a rate or average` yields the class alone, and a heading that
is not an exception at all (a wrong number, a swallowed `except`) yields no match - those entries stay in
the index for reading and are never claimed for a traceback they do not describe.

Run: `python3 scripts/generate_error_index.py` (writes), `--check` (fails when stale).
Exit-code family: typed (0 pass, 1 stale, 2 bad arguments).
"""

import argparse
import json
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOC = os.path.join(ROOT, "docs", "ERROR_EXPLAINER.md")
OUT = os.path.join(ROOT, "app", "src", "data", "errorIndex.ts")

ENTRY_RE = re.compile(r"^## (\d+)\. (.+)$", re.MULTILINE)
HEAD_CODE = re.compile(r"^`([^`]+)`")
EXCEPTION_NAME = re.compile(
    r"^[A-Za-z_][\w.]*(?:Error|Exception|Warning|Interrupt|Exit|StopIteration)$"
)
LINK_RE = re.compile(r"\[([^\]]+)\]\(([^)\s]+)\)")

HEADER = '''// Generated by `scripts/generate_error_index.py` from `docs/ERROR_EXPLAINER.md` - do not edit.
// `python3 scripts/generate_error_index.py --check` fails when this file and that page disagree.
//
// Each entry is the page's own words, shaped for the runner: the symptom a traceback is matched by,
// one sentence of what it means, the checks to try first, and the page that teaches it.

export interface ErrorIndexSource {
  /** The page, as the explainer cites it (a lesson id or a document). */
  label: string;
  /** Its path from the repository root. */
  path: string;
}

export interface ErrorIndexMatch {
  /** The exception class the traceback must end with. */
  exception: string;
  /** Text the exception's own message must contain, or null for "any message of that class". */
  pattern: string | null;
}

export interface ErrorIndexEntry {
  /** The page's numbering, quoted in the card and in a bug report. */
  number: number;
  /** The heading: the symptom a learner sees. */
  title: string;
  /** `**What it means.**`, as one line. */
  means: string;
  /** `**Check first.**`, in the page's order. */
  checks: string[];
  source: ErrorIndexSource;
  /** Null for an entry about a wrong number or a habit, which no traceback can name. */
  match: ErrorIndexMatch | null;
}

export const ERROR_INDEX: ErrorIndexEntry[] = [
'''


def entries(text):
    """`## N. Title` blocks with their bodies, in order."""
    matches = list(ENTRY_RE.finditer(text))
    out = []
    for index, match in enumerate(matches):
        end = matches[index + 1].start() if index + 1 < len(matches) else len(text)
        out.append((int(match.group(1)), match.group(2).strip(), text[match.end():end]))
    return out


def plain(markdown):
    """The words without the Markdown a card would print literally."""
    text = markdown.replace("`", "")
    text = re.sub(r"\*\*([^*]+)\*\*", r"\1", text)
    text = re.sub(r"(?<!\*)\*([^*\n]+)\*(?!\*)", r"\1", text)
    text = re.sub(r"\[([^\]]+)\]\([^)]*\)", r"\1", text)
    return re.sub(r"\s+", " ", text).strip()


def paragraph_after(body, label):
    """The text of a labelled paragraph, collapsed: `**What it means.** ...`."""
    at = body.find(label)
    if at < 0:
        raise SystemExit(f"entry is missing {label!r} in {DOC}")
    rest = body[at + len(label):]
    lines = []
    for line in rest.split("\n"):
        if lines and not line.strip():
            break
        if line.strip():
            lines.append(line.strip())
    return plain(" ".join(lines))


def bullets_after(body, label, stop_label):
    """The `- ` bullets of a labelled list, wrapped lines rejoined."""
    start = body.find(label)
    if start < 0:
        raise SystemExit(f"entry is missing {label!r} in {DOC}")
    end = body.find(stop_label, start)
    block = body[start:end if end >= 0 else len(body)]
    bullets = []
    for line in block.split("\n"):
        if line.startswith("- "):
            bullets.append(line[2:].strip())
        elif bullets and line.strip():
            bullets[-1] += " " + line.strip()
    if len(bullets) < 2:
        raise SystemExit(f"entry has {len(bullets)} check-first bullets in {DOC}")
    return [plain(bullet) for bullet in bullets]


def source_after(body, label):
    """The first relative citation under `**Where it comes from.**`."""
    start = body.find(label)
    if start < 0:
        raise SystemExit(f"entry is missing {label!r} in {DOC}")
    block = body[start + len(label):]
    for label_text, target in LINK_RE.findall(block):
        if target.startswith(("http://", "https://", "#")):
            continue
        path = os.path.normpath(os.path.join("docs", target.split("#")[0]))
        return {"label": plain(label_text), "path": path}
    raise SystemExit(f"entry cites no page under {label!r} in {DOC}")


def match_for(raw_title):
    """The exception a heading names, and the message text it quotes, when it names one."""
    found = HEAD_CODE.match(raw_title)
    token = found.group(1) if found else ""
    if not token:
        return None
    if ": " in token:
        exception, pattern = token.split(": ", 1)
        if EXCEPTION_NAME.match(exception):
            return {"exception": exception, "pattern": plain(pattern)}
        return None
    if EXCEPTION_NAME.match(token):
        return {"exception": token, "pattern": None}
    return None


def build():
    with open(DOC, encoding="utf-8") as handle:
        text = handle.read()
    parsed = entries(text)
    if len(parsed) < 15:
        raise SystemExit(f"expected at least 15 entries in {DOC}, found {len(parsed)}")
    chunks = []
    for number, raw_title, body in parsed:
        entry = {
            "number": number,
            "title": plain(raw_title),
            "means": paragraph_after(body, "**What it means.**"),
            "checks": bullets_after(body, "**Check first.**", "**Where it comes from.**"),
            "source": source_after(body, "**Where it comes from.**"),
            "match": match_for(raw_title),
        }
        chunks.append("  " + json.dumps(entry, ensure_ascii=False) + ",")
    return HEADER + "\n".join(chunks) + "\n];\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="fail when the data file is stale")
    args = parser.parse_args()

    generated = build()
    if args.check:
        try:
            with open(OUT, encoding="utf-8") as handle:
                current = handle.read()
        except FileNotFoundError:
            print(f"{OUT} is missing - run python3 scripts/generate_error_index.py", file=sys.stderr)
            return 1
        if current != generated:
            print(
                f"{OUT} does not match {DOC} - run python3 scripts/generate_error_index.py",
                file=sys.stderr,
            )
            return 1
        print(f"{OUT} matches {DOC}")
        return 0

    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8") as handle:
        handle.write(generated)
    print(f"wrote {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
